#!/usr/bin/env python3
"""Generate src/components/icons.generated.ts from docs/reference/svgs.json.

The reference page inlines every icon as an <svg>. We keep the exact bytes (viewBox, presentation
attributes, path data) and only give each one a semantic name. Re-run after changing NAMES.
"""
import json, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
svgs = json.load(open(ROOT / 'docs/reference/svgs.json', encoding='utf-8'))
NAMES = ['logo','globe','menu','share','heart','grid','laurel','star','outdoor','fan','door','chevronRight',
 'kitchen','wifi','workspace','parking','pool','hotTub','pets','camera','coAlarm','smokeAlarm','chevronLeft',
 'keyboard','chevronDown','flag','spray','checkCircle','key','chat','map','tag','search','plus','minus','house',
 'cake','school','shield','calendar','back','close','prev','next','hairdryer','cleaningProducts','shampoo',
 'hotWater','showerGel','washer','hangers','bedLinen','blinds','iron','wardrobe','cot','tv','ac','fridge',
 'microwave','cutlery','kettle','coffee','wine','toaster','blender','cooker','entrance','patio','outdoorDining',
 'gym','longTerm']
SKIP = {'aria-hidden', 'role', 'focusable', 'xmlns'}
def camel(k): return re.sub(r'-(\w)', lambda m: m.group(1).upper(), k)
def style_obj(s):
    out = {}
    for decl in filter(None, s.split(';')):
        k, v = decl.split(':', 1); out[camel(k.strip())] = v.strip()
    return out
icons = {}
for name, svg in zip(NAMES, svgs):
    open_tag = re.match(r'<svg[^>]*>', svg).group(0)
    attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', open_tag))
    body = svg[len(open_tag):-len('</svg>')]
    entry = {'viewBox': attrs.pop('viewBox'), 'body': body}
    style = attrs.pop('style', None)
    if style: entry['style'] = style_obj(style)
    extra = {camel(k): v for k, v in attrs.items() if k not in SKIP}
    if extra: entry['attrs'] = extra
    icons[name] = entry
# Filled heart is only present in the DOM while "Saved"; captured separately from the live page.
icons['heartFilled'] = {'viewBox': '0 0 32 32', 'style': {'display': 'block', 'height': '100%', 'width': '100%', 'fill': 'currentColor'},
  'body': '<path d="M16 28C7 22 3 16 3 10.5A6.5 6.5 0 0 1 16 8a6.5 6.5 0 0 1 13 2.5C29 16 25 22 16 28z"></path>'}
out = ROOT / 'src/components/icons.generated.ts'
lines = ['// GENERATED by scripts/gen-icons.py from docs/reference/svgs.json — do not edit by hand.',
         "import type { CSSProperties } from 'react';",
         'export interface IconDef { viewBox: string; body: string; style?: CSSProperties; attrs?: Record<string, string> }',
         'export const ICONS = {']
for name, e in icons.items():
    lines.append(f'  {name}: {json.dumps(e, ensure_ascii=False)},')
lines += ['} satisfies Record<string, IconDef>;', 'export type IconName = keyof typeof ICONS;', '']
out.write_text('\n'.join(lines), encoding='utf-8')
print('wrote', out, len(icons), 'icons')
